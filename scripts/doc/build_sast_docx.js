const fig = (rel, widthPx) => {
  const file = path.join(ROOT, rel);
  if (!fs.existsSync(file)) {
    return new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [new TextRun({ text: `[缺图: ${rel}]`, font: SONG, size: 21, color: 'CC0000' })],
    });
  }
  // 读取 PNG 真实尺寸, 等比缩放
  const head = fs.readFileSync(file).subarray(0, 26);
  let w = 1000, hgt = 700;
  if (head.subarray(0, 8).toString('binary') === '\x89PNG\r\n\x1a\n') {
    w = head.readUInt32BE(16); hgt = head.readUInt32BE(20);
  }
  const heightPx = Math.round(widthPx * hgt / w);
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 120 },
    children: [new ImageRun({
      type: 'png',
      data: fs.readFileSync(file),
      transformation: { width: widthPx, height: heightPx },
      altText: { title: rel, description: rel, name: path.basename(rel) },
    })],
  });
};

